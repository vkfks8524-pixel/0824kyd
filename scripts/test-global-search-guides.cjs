'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const {posts,ranking,checked}=require('./global-search-guides.cjs');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const library=read('posts/index.html'),home=read('index.html'),rss=read('rss.xml'),sitemap=read('sitemap.xml');
const escape=value=>value.replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;');
assert.deepEqual(ranking.rows.map(row=>[row.rank,row.query,row.volume]),[[1,'chatgpt',811195000],[2,'whatsapp web',482840000],[3,'youtube',383003000],[4,'chat gpt',320598000],[5,'translate',235233000]]);
assert.equal(ranking.updated,'2026-09-01');assert.equal(checked,'2026-10-05');
assert.equal(Object.keys(posts).length,5);
assert.equal(new Set(Object.values(posts).map(post=>post.title)).size,5);
assert.equal(new Set(Object.values(posts).map(post=>post.description)).size,5);
assert.equal((library.match(/id="web-ai"/g)||[]).length,1);
assert.equal((library.match(/href="#web-ai"/g)||[]).length,1);
assert(library.includes('five queries, four distinct topics'));
assert(library.includes('not a Google-issued real-time ranking'));
assert(library.includes('not today’s searches, unique people or visits to KYD'));
assert(library.includes('broader than Google Translate'));
assert(library.includes(ranking.url) && library.includes(ranking.methodology));
for(const row of ranking.rows)assert(library.includes(row.volume.toLocaleString('en-US')));
for(const [slug,data] of Object.entries(posts)){
 const file='posts/'+slug+'/index.html',html=read(file),url='https://www.kyd.kr/posts/'+slug+'/';
 assert.equal(read('public/'+file),html);
 assert(html.includes('<h1>'+escape(data.title)+'</h1>'));
 assert(html.includes('<meta name="description" content="'+escape(data.description)+'">'));
 assert(html.includes('rel="canonical" href="'+url+'"'));
 const schema=JSON.parse(html.match(/<script type="application\/ld\+json">(.*?)<\/script>/s)[1]);
 assert.equal(schema.headline,data.title);assert.equal(schema.description,data.description);
 assert.equal(schema.datePublished,checked);assert.equal(schema.dateModified,checked);assert.equal(schema.inLanguage,'en');assert.equal(schema.mainEntityOfPage,url);
 assert(!schema.image && !html.includes('<img'), 'No invented product or test imagery');
 assert(html.includes('class="author-box"') && html.includes('class="sources"') && html.includes('Automation-assisted'));
 assert(!html.includes('English adaptation:') && !html.includes('Translation does not renew'), 'Fresh article is not labeled as an old adaptation');
 const sources=html.match(/<section class="sources"[\s\S]*?<\/section>/)[0];
 for(const [source] of data.sources)assert(sources.includes(escape(source)), 'Missing source '+source);
 const headingIds=[...html.matchAll(/<h2 id="([^"]+)">/g)].map(match=>match[1]);
 assert(headingIds.length>4);assert.equal(new Set(headingIds).size,headingIds.length);
 for(const id of headingIds)assert(html.includes('href="#'+id+'"'));
 for(const related of data.related)assert(html.includes('href="/posts/'+related+'/"'));
 assert(library.includes('href="/posts/'+slug+'/"') && home.includes('href="/posts/'+slug+'/"'));
 assert(sitemap.includes('<loc>'+url+'</loc>') && rss.includes('<link>'+url+'</link>'));
 assert(!/[가-힣]/.test(html));
}
assert(read('posts/whatsapp-web-link-unlink-devices/index.html').includes('not a forensic investigation'));
assert(read('posts/youtube-watch-history-recommendations/index.html').includes('remove both search and watch activity'));
assert(read('posts/google-translate-check-before-sending/index.html').includes('not independent proof'));
assert(read('posts/chatgpt-privacy-before-uploading/index.html').includes('not a guarantee of anonymity'));
console.log('PASS: five distinct source-based English guides, ranking snapshot and aliases, no fabricated test/photo claims, canonical/Article metadata, publication/source dates, TOCs, internal discovery, RSS and deployment mirrors.');
